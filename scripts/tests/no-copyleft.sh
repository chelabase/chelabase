#!/usr/bin/env bash
# The identity service's image ships its production npm dependencies (Better Auth and what it
# pulls in). None of them may be under the GPL or the AGPL, and each must be listed, with its
# licence text, in THIRD_PARTY_NOTICES.md.
#
#   bash scripts/tests/no-copyleft.sh          check (wired into `just check`)
#   bash scripts/tests/no-copyleft.sh --write  rewrite THIRD_PARTY_NOTICES.md from the lockfile's
#                                              installed packages, then check
#
# The package set is `pnpm --filter @chelabase/identity licenses list --prod`, the same set
# infra/images/identity.Dockerfile deploys (`pnpm --filter @chelabase/identity deploy --prod`).
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
notices=THIRD_PARTY_NOTICES.md
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

pnpm --filter @chelabase/identity licenses list --prod --json >"$tmp/licenses.json" 2>"$tmp/err" ||
  { cat "$tmp/err" >&2; echo "no-copyleft: pnpm licenses list failed (run pnpm install)" >&2; exit 1; }
# One line per package: name, version, licence, homepage, install path.
jq -r 'to_entries[] | .key as $l | .value[] | . as $p | .versions | to_entries[]
  | [$p.name, .value, $l, ($p.homepage // ""), ($p.paths[.key] // $p.paths[0])] | @tsv' \
  "$tmp/licenses.json" | sort -f >"$tmp/packages.tsv"
n="$(wc -l <"$tmp/packages.tsv")"
((n > 0)) || { echo "no-copyleft: pnpm listed no production dependency for @chelabase/identity" >&2; exit 1; }
grep -q '^better-auth	' "$tmp/packages.tsv" ||
  { echo "no-copyleft: better-auth isn't among the listed packages: the listing is wrong" >&2; exit 1; }

bad=0
# GPL and AGPL in any version or combination; an unknown licence can't be cleared either.
while IFS=$'\t' read -r name version license _ _; do
  if grep -qE '(^|[^L])GPL|AGPL' <<<"$license" || [[ -z "$license" || "$license" == Unknown ]]; then
    echo "no-copyleft: $name@$version is licensed '$license'" >&2
    bad=1
  fi
done <"$tmp/packages.tsv"

if [[ "${1:-}" == --write ]]; then
  {
    echo "# Third-party notices"
    echo
    echo "The identity service image (\`infra/images/identity.Dockerfile\`) ships these npm packages:"
    echo "the production dependencies of \`services/identity\`, Better Auth and what it pulls in."
    echo "Generated by \`bash scripts/tests/no-copyleft.sh --write\`; \`just check\` fails when it is"
    echo "out of date or when a package is under the GPL or the AGPL."
    echo
    echo "| Package | Version | Licence |"
    echo "|---|---|---|"
    while IFS=$'\t' read -r name version license _ _; do
      echo "| \`$name\` | $version | $license |"
    done <"$tmp/packages.tsv"
    while IFS=$'\t' read -r name version license homepage path; do
      echo
      echo "## $name $version"
      echo
      echo "Licence: $license${homepage:+. Home: <$homepage>}"
      text="$(find "$path" -maxdepth 1 -type f \( -iname 'license*' -o -iname 'licence*' -o -iname 'copying*' \) | sort | head -n1)"
      if [[ -n "$text" ]]; then
        echo
        echo '```text'
        tr -d '\r' <"$text" | sed -e 's/[[:space:]]*$//'
        echo '```'
      else
        echo
        echo "The package ships no licence file; its licence is $license."
      fi
    done <"$tmp/packages.tsv"
  } >"$notices"
  echo "no-copyleft: wrote $notices ($n packages)"
fi

[[ -f $notices ]] || { echo "no-copyleft: $notices is missing: run bash scripts/tests/no-copyleft.sh --write" >&2; exit 1; }
while IFS=$'\t' read -r name version license _ _; do
  grep -qF "| \`$name\` | $version | $license |" "$notices" || {
    echo "no-copyleft: $notices doesn't list $name $version ($license): run bash scripts/tests/no-copyleft.sh --write" >&2
    bad=1
  }
done <"$tmp/packages.tsv"
listed="$(grep -cE '^\| `' "$notices" || true)"
[[ "$listed" == "$n" ]] || {
  echo "no-copyleft: $notices lists $listed packages, the image ships $n: run bash scripts/tests/no-copyleft.sh --write" >&2
  bad=1
}
[[ $bad -eq 0 ]] && echo "no-copyleft: ok ($n packages, none GPL or AGPL)"
exit $bad
